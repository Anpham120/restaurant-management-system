-- ===== Hàm và trigger (chép nguyên văn từ README phân hệ) =====

-- Nguồn: 03-quan-ly-don-hang/README.md
-- Phiên gắn cố định một bàn từ lúc mở đến khi đóng (ORD-15)
CREATE FUNCTION fn_table_sessions_fixed_table() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.dining_table_id IS DISTINCT FROM OLD.dining_table_id THEN
        RAISE EXCEPTION 'Phiên % gắn cố định với bàn %, không được đổi bàn', OLD.id, OLD.dining_table_id;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_table_sessions_fixed_table BEFORE UPDATE OF dining_table_id ON table_sessions
FOR EACH ROW EXECUTE FUNCTION fn_table_sessions_fixed_table();

-- Nguồn: 05-quan-ly-tai-chinh/README.md
-- Bản đối soát bất biến (FIN-10): chỉ được đổi status CURRENT → SUPERSEDED, không sửa số liệu, không xóa
CREATE FUNCTION fn_reconciliations_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Không được xóa bản đối soát %', OLD.id;
    END IF;
    IF (to_jsonb(NEW) - 'status') IS DISTINCT FROM (to_jsonb(OLD) - 'status')
       OR NOT (OLD.status = 'CURRENT' AND NEW.status IN ('CURRENT', 'SUPERSEDED')) THEN
        RAISE EXCEPTION 'Bản đối soát % chỉ được chuyển CURRENT sang SUPERSEDED', OLD.id;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_daily_cash_reconciliations_immutable BEFORE UPDATE OR DELETE ON daily_cash_reconciliations
FOR EACH ROW EXECUTE FUNCTION fn_reconciliations_immutable();
