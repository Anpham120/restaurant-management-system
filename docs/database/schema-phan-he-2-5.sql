-- ===== Phân hệ 2 – Quản lý thực đơn =====

CREATE TABLE menu_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    sort_order INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL,
    CONSTRAINT pk_menu_categories PRIMARY KEY (id)
);

CREATE TABLE menu_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    menu_category_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    price DECIMAL(12,2) NOT NULL,
    image_url VARCHAR(255),
    is_active BOOLEAN NOT NULL,
    CONSTRAINT pk_menu_items PRIMARY KEY (id),
    CONSTRAINT ck_menu_items_price CHECK (price >= 0)
);

CREATE TABLE recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    menu_item_id BIGINT NOT NULL,
    version INTEGER NOT NULL,
    is_current BOOLEAN NOT NULL,
    CONSTRAINT pk_recipes PRIMARY KEY (id),
    CONSTRAINT uq_recipes_menu_item_version UNIQUE (menu_item_id, version),
    CONSTRAINT uq_recipes_id_menu_item UNIQUE (id, menu_item_id),
    CONSTRAINT ck_recipes_version CHECK (version >= 1)
);

CREATE TABLE recipe_ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    recipe_id BIGINT NOT NULL,
    ingredient_id BIGINT NOT NULL,
    quantity_per_serving DECIMAL(12,3) NOT NULL,
    CONSTRAINT pk_recipe_ingredients PRIMARY KEY (id),
    CONSTRAINT uq_recipe_ingredients_recipe_ingredient UNIQUE (recipe_id, ingredient_id),
    CONSTRAINT ck_recipe_ingredients_quantity_per_serving CHECK (quantity_per_serving > 0)
);

CREATE TABLE daily_menus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    business_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    published_at TIMESTAMPTZ,
    CONSTRAINT pk_daily_menus PRIMARY KEY (id),
    CONSTRAINT uq_daily_menus_business_date UNIQUE (business_date),
    CONSTRAINT ck_daily_menus_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED'))
);

CREATE TABLE daily_menu_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    daily_menu_id BIGINT NOT NULL,
    menu_item_id BIGINT NOT NULL,
    recipe_id BIGINT NOT NULL,
    quota_total INTEGER NOT NULL,
    is_paused BOOLEAN NOT NULL,
    pause_reason VARCHAR(255),
    CONSTRAINT pk_daily_menu_items PRIMARY KEY (id),
    CONSTRAINT uq_daily_menu_items_daily_menu_menu_item UNIQUE (daily_menu_id, menu_item_id),
    CONSTRAINT ck_daily_menu_items_quota_total CHECK (quota_total >= 0)
);

-- ===== Phân hệ 3 – Quản lý đơn hàng =====

CREATE TABLE dining_tables (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(20) NOT NULL,
    capacity INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT pk_dining_tables PRIMARY KEY (id),
    CONSTRAINT uq_dining_tables_code UNIQUE (code),
    CONSTRAINT ck_dining_tables_status CHECK (status IN ('AVAILABLE', 'OCCUPIED')),
    CONSTRAINT ck_dining_tables_capacity CHECK (capacity > 0)
);

CREATE TABLE table_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    dining_table_id BIGINT NOT NULL,
    opened_at TIMESTAMPTZ NOT NULL,
    closed_at TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT pk_table_sessions PRIMARY KEY (id),
    CONSTRAINT ck_table_sessions_status CHECK (status IN ('OPEN', 'CLOSED'))
);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    table_session_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT pk_orders PRIMARY KEY (id),
    CONSTRAINT uq_orders_table_session UNIQUE (table_session_id),
    CONSTRAINT ck_orders_status CHECK (status IN ('OPEN', 'CLOSED', 'CANCELLED'))
);

CREATE TABLE order_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id BIGINT NOT NULL,
    waiter_id BIGINT NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL,
    request_key VARCHAR(64) NOT NULL,
    CONSTRAINT pk_order_batches PRIMARY KEY (id),
    CONSTRAINT uq_order_batches_request_key UNIQUE (request_key)
);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_batch_id BIGINT NOT NULL,
    daily_menu_item_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price DECIMAL(12,2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    has_stock_exception BOOLEAN NOT NULL,
    note VARCHAR(255),
    CONSTRAINT pk_order_items PRIMARY KEY (id),
    CONSTRAINT ck_order_items_status CHECK (status IN ('PENDING', 'ACCEPTED', 'IN_KITCHEN', 'COOKING', 'READY', 'CANCELLED', 'REJECTED')),
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0 AND unit_price >= 0)
);

CREATE TABLE order_item_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_item_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    from_status VARCHAR(20),
    to_status VARCHAR(20) NOT NULL,
    reason VARCHAR(255),
    kitchen_confirmed BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_order_item_events PRIMARY KEY (id),
    CONSTRAINT ck_order_item_events_from_status CHECK (from_status IN ('PENDING', 'ACCEPTED', 'IN_KITCHEN', 'COOKING', 'READY', 'CANCELLED', 'REJECTED')),
    CONSTRAINT ck_order_item_events_to_status CHECK (to_status IN ('PENDING', 'ACCEPTED', 'IN_KITCHEN', 'COOKING', 'READY', 'CANCELLED', 'REJECTED'))
);

CREATE TABLE invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id BIGINT NOT NULL,
    total DECIMAL(12,2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT pk_invoices PRIMARY KEY (id),
    CONSTRAINT uq_invoices_order UNIQUE (order_id),
    CONSTRAINT ck_invoices_status CHECK (status IN ('DRAFT', 'PAYMENT_PENDING', 'PAID')),
    CONSTRAINT ck_invoices_total CHECK (total >= 0)
);

CREATE TABLE payment_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    invoice_id BIGINT NOT NULL,
    waiter_id BIGINT NOT NULL,
    cashier_id BIGINT,
    amount_due DECIMAL(12,2) NOT NULL,
    cash_received DECIMAL(12,2),
    cash_counted DECIMAL(12,2),
    change_amount DECIMAL(12,2),
    method VARCHAR(20) NOT NULL,
    status VARCHAR(30) NOT NULL,
    payment_reference VARCHAR(64),
    cancel_reason VARCHAR(255),
    CONSTRAINT pk_payment_requests PRIMARY KEY (id),
    CONSTRAINT uq_payment_requests_payment_reference UNIQUE (payment_reference),
    CONSTRAINT ck_payment_requests_method CHECK (method IN ('QR', 'CASH')),
    CONSTRAINT ck_payment_requests_status CHECK (status IN ('REQUESTED', 'APPROVED', 'WAITING_TRANSFER', 'WAITING_CASH_HANDOVER', 'PAID', 'CANCELLED')),
    CONSTRAINT ck_payment_requests_amount_due CHECK (amount_due >= 0),
    CONSTRAINT ck_payment_requests_cash_received CHECK (cash_received >= 0),
    CONSTRAINT ck_payment_requests_cash_counted CHECK (cash_counted >= 0),
    CONSTRAINT ck_payment_requests_change_amount CHECK (change_amount >= 0),
    CONSTRAINT ck_payment_requests_change CHECK (change_amount = GREATEST(cash_received - amount_due, 0)),
    CONSTRAINT ck_payment_requests_change_presence CHECK ((cash_received IS NULL) = (change_amount IS NULL)),
    CONSTRAINT ck_payment_requests_payment_reference CHECK ((payment_reference IS NULL OR method = 'QR') AND (method <> 'QR' OR status NOT IN ('WAITING_TRANSFER', 'PAID') OR payment_reference IS NOT NULL)),
    CONSTRAINT ck_payment_requests_qr_no_cash CHECK (method <> 'QR' OR (cash_received IS NULL AND cash_counted IS NULL AND change_amount IS NULL)),
    CONSTRAINT ck_payment_requests_cash_paid CHECK (method <> 'CASH' OR status <> 'PAID' OR (cash_received IS NOT NULL AND cash_counted IS NOT NULL AND cash_counted = cash_received AND cash_received >= amount_due)),
    CONSTRAINT ck_payment_requests_cancel_reason CHECK (status <> 'CANCELLED' OR cancel_reason IS NOT NULL)
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    payment_request_id BIGINT NOT NULL,
    payment_webhook_event_id BIGINT,
    amount DECIMAL(12,2) NOT NULL,
    method VARCHAR(20) NOT NULL,
    paid_at TIMESTAMPTZ NOT NULL,
    business_date DATE NOT NULL,
    CONSTRAINT pk_payments PRIMARY KEY (id),
    CONSTRAINT uq_payments_payment_request UNIQUE (payment_request_id),
    CONSTRAINT uq_payments_payment_webhook_event UNIQUE (payment_webhook_event_id),
    CONSTRAINT ck_payments_method CHECK (method IN ('QR', 'CASH')),
    CONSTRAINT ck_payments_amount CHECK (amount > 0),
    CONSTRAINT ck_payments_qr_webhook CHECK ((method = 'QR') = (payment_webhook_event_id IS NOT NULL))
);

CREATE TABLE payment_webhook_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    payment_request_id BIGINT,
    provider_transaction_code VARCHAR(64) NOT NULL,
    payment_reference VARCHAR(64),
    amount DECIMAL(12,2) NOT NULL,
    processing_result VARCHAR(20) NOT NULL,
    received_at TIMESTAMPTZ NOT NULL,
    raw_payload TEXT,
    CONSTRAINT pk_payment_webhook_events PRIMARY KEY (id),
    CONSTRAINT uq_payment_webhook_events_provider_transaction_code UNIQUE (provider_transaction_code),
    CONSTRAINT uq_payment_webhook_events_id_request UNIQUE (id, payment_request_id),
    CONSTRAINT ck_payment_webhook_events_processing_result CHECK (processing_result IN ('PROCESSED', 'MISMATCH', 'AFTER_CANCEL')),
    CONSTRAINT ck_payment_webhook_events_processed_request CHECK (processing_result <> 'PROCESSED' OR payment_request_id IS NOT NULL)
);

-- ===== Phân hệ 4 – Quản lý kho & nguyên liệu =====

CREATE TABLE ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    base_unit VARCHAR(20) NOT NULL,
    min_quantity DECIMAL(12,3) NOT NULL,
    is_expiry_tracked BOOLEAN NOT NULL,
    is_active BOOLEAN NOT NULL,
    CONSTRAINT pk_ingredients PRIMARY KEY (id),
    CONSTRAINT uq_ingredients_name UNIQUE (name),
    CONSTRAINT ck_ingredients_min_quantity CHECK (min_quantity >= 0)
);

CREATE TABLE stock_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    supplier_name VARCHAR(100),
    status VARCHAR(20) NOT NULL,
    note VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL,
    confirmed_by_id BIGINT,
    confirmed_at TIMESTAMPTZ,
    CONSTRAINT pk_stock_receipts PRIMARY KEY (id),
    CONSTRAINT ck_stock_receipts_status CHECK (status IN ('DRAFT', 'CONFIRMED')),
    CONSTRAINT ck_stock_receipts_confirmed CHECK (status <> 'CONFIRMED' OR (confirmed_by_id IS NOT NULL AND confirmed_at IS NOT NULL))
);

CREATE TABLE stock_receipt_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    stock_receipt_id BIGINT NOT NULL,
    ingredient_id BIGINT NOT NULL,
    input_quantity DECIMAL(12,3) NOT NULL,
    input_unit VARCHAR(20) NOT NULL,
    conversion_factor DECIMAL(12,3) NOT NULL,
    quantity DECIMAL(12,3) NOT NULL,
    unit_price DECIMAL(12,2) NOT NULL,
    lot_code VARCHAR(50),
    expiry_date DATE,
    CONSTRAINT pk_stock_receipt_items PRIMARY KEY (id),
    CONSTRAINT uq_stock_receipt_items_id_ingredient UNIQUE (id, ingredient_id),
    CONSTRAINT uq_stock_receipt_items_lot UNIQUE NULLS NOT DISTINCT (stock_receipt_id, ingredient_id, lot_code, expiry_date),
    CONSTRAINT ck_stock_receipt_items_input_quantity CHECK (input_quantity > 0 AND conversion_factor > 0),
    CONSTRAINT ck_stock_receipt_items_unit_price CHECK (unit_price >= 0),
    CONSTRAINT ck_stock_receipt_items_quantity CHECK (quantity = ROUND(input_quantity * conversion_factor, 3))
);

CREATE TABLE inventory_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ingredient_id BIGINT NOT NULL,
    stock_receipt_item_id BIGINT NOT NULL,
    lot_code VARCHAR(50),
    expiry_date DATE,
    received_at TIMESTAMPTZ NOT NULL,
    quantity_on_hand DECIMAL(12,3) NOT NULL,
    reserved_quantity DECIMAL(12,3) NOT NULL,
    is_usable BOOLEAN NOT NULL,
    unusable_reason VARCHAR(255),
    unusable_marked_by_id BIGINT,
    unusable_marked_at TIMESTAMPTZ,
    CONSTRAINT pk_inventory_batches PRIMARY KEY (id),
    CONSTRAINT uq_inventory_batches_stock_receipt_item UNIQUE (stock_receipt_item_id),
    CONSTRAINT ck_inventory_batches_quantity_on_hand CHECK (quantity_on_hand >= 0),
    CONSTRAINT ck_inventory_batches_reserved_quantity CHECK (reserved_quantity >= 0),
    CONSTRAINT ck_inventory_batches_unusable_reason CHECK (is_usable OR unusable_reason IS NOT NULL)
);

CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    inventory_batch_id BIGINT NOT NULL,
    movement_type VARCHAR(20) NOT NULL,
    quantity_delta DECIMAL(12,3) NOT NULL,
    balance_after DECIMAL(12,3) NOT NULL,
    order_item_id BIGINT,
    stock_count_item_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_stock_movements PRIMARY KEY (id),
    CONSTRAINT uq_stock_movements_stock_count_item UNIQUE (stock_count_item_id),
    CONSTRAINT ck_stock_movements_movement_type CHECK (movement_type IN ('RECEIPT', 'CONSUMPTION', 'ADJUSTMENT')),
    CONSTRAINT ck_stock_movements_quantity_delta CHECK (quantity_delta <> 0),
    CONSTRAINT ck_stock_movements_balance_after CHECK (balance_after >= 0),
    CONSTRAINT ck_stock_movements_source CHECK ((movement_type = 'CONSUMPTION' AND order_item_id IS NOT NULL AND stock_count_item_id IS NULL AND quantity_delta < 0) OR (movement_type = 'ADJUSTMENT' AND stock_count_item_id IS NOT NULL AND order_item_id IS NULL) OR (movement_type = 'RECEIPT' AND order_item_id IS NULL AND stock_count_item_id IS NULL AND quantity_delta > 0))
);

CREATE TABLE stock_reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_item_id BIGINT NOT NULL,
    inventory_batch_id BIGINT NOT NULL,
    quantity DECIMAL(12,3) NOT NULL,
    status VARCHAR(20) NOT NULL,
    release_reason VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL,
    closed_at TIMESTAMPTZ,
    CONSTRAINT pk_stock_reservations PRIMARY KEY (id),
    CONSTRAINT ck_stock_reservations_status CHECK (status IN ('ACTIVE', 'CONSUMED', 'RELEASED')),
    CONSTRAINT ck_stock_reservations_release_reason CHECK (release_reason IN ('ITEM_CANCELLED', 'ITEM_EDITED', 'LOT_UNAVAILABLE')),
    CONSTRAINT ck_stock_reservations_quantity CHECK (quantity > 0),
    CONSTRAINT ck_stock_reservations_released CHECK (status <> 'RELEASED' OR release_reason IS NOT NULL),
    CONSTRAINT ck_stock_reservations_closed_at CHECK (status NOT IN ('CONSUMED', 'RELEASED') OR closed_at IS NOT NULL)
);

CREATE TABLE stock_counts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    status VARCHAR(20) NOT NULL,
    note VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL,
    confirmed_by_id BIGINT,
    confirmed_at TIMESTAMPTZ,
    CONSTRAINT pk_stock_counts PRIMARY KEY (id),
    CONSTRAINT ck_stock_counts_status CHECK (status IN ('DRAFT', 'CONFIRMED')),
    CONSTRAINT ck_stock_counts_confirmed CHECK (status <> 'CONFIRMED' OR (confirmed_by_id IS NOT NULL AND confirmed_at IS NOT NULL))
);

CREATE TABLE stock_count_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    stock_count_id BIGINT NOT NULL,
    inventory_batch_id BIGINT NOT NULL,
    book_quantity DECIMAL(12,3) NOT NULL,
    actual_quantity DECIMAL(12,3) NOT NULL,
    difference DECIMAL(12,3) NOT NULL,
    reason VARCHAR(255),
    CONSTRAINT pk_stock_count_items PRIMARY KEY (id),
    CONSTRAINT uq_stock_count_items_stock_count_inventory_batch UNIQUE (stock_count_id, inventory_batch_id),
    CONSTRAINT ck_stock_count_items_actual_quantity CHECK (actual_quantity >= 0),
    CONSTRAINT ck_stock_count_items_difference CHECK (difference = actual_quantity - book_quantity),
    CONSTRAINT ck_stock_count_items_reason CHECK (difference = 0 OR reason IS NOT NULL)
);

-- ===== Phân hệ 5 – Quản lý tài chính =====

CREATE TABLE operating_expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    business_date DATE NOT NULL,
    category VARCHAR(30) NOT NULL,
    description VARCHAR(255) NOT NULL,
    amount DECIMAL(12,2) NOT NULL,
    payment_method VARCHAR(20) NOT NULL,
    fund_source VARCHAR(20) NOT NULL,
    stock_receipt_id BIGINT,
    recorded_by_id BIGINT NOT NULL,
    paid_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    request_key VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL,
    void_reason VARCHAR(255),
    voided_by_id BIGINT,
    voided_at TIMESTAMPTZ,
    CONSTRAINT pk_operating_expenses PRIMARY KEY (id),
    CONSTRAINT uq_operating_expenses_request_key UNIQUE (request_key),
    CONSTRAINT ck_operating_expenses_category CHECK (category IN ('INGREDIENT', 'SUPPLIES', 'TRANSPORT', 'OTHER')),
    CONSTRAINT ck_operating_expenses_payment_method CHECK (payment_method IN ('CASH', 'TRANSFER')),
    CONSTRAINT ck_operating_expenses_fund_source CHECK (fund_source IN ('COUNTER', 'OTHER')),
    CONSTRAINT ck_operating_expenses_status CHECK (status IN ('RECORDED', 'VOIDED')),
    CONSTRAINT ck_operating_expenses_amount CHECK (amount > 0),
    CONSTRAINT ck_operating_expenses_counter_cash CHECK (fund_source <> 'COUNTER' OR payment_method = 'CASH'),
    CONSTRAINT ck_operating_expenses_receipt_ingredient CHECK (stock_receipt_id IS NULL OR category = 'INGREDIENT'),
    CONSTRAINT ck_operating_expenses_voided CHECK (status <> 'VOIDED' OR (void_reason IS NOT NULL AND voided_by_id IS NOT NULL AND voided_at IS NOT NULL)),
    CONSTRAINT ck_operating_expenses_paid_at CHECK (paid_at <= created_at)
);

CREATE TABLE daily_cash_reconciliations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    business_date DATE NOT NULL,
    version INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    opening_cash DECIMAL(12,2) NOT NULL,
    cash_sales DECIMAL(12,2) NOT NULL,
    cash_expenses DECIMAL(12,2) NOT NULL,
    expected_cash DECIMAL(12,2) NOT NULL,
    actual_cash DECIMAL(12,2) NOT NULL,
    difference DECIMAL(12,2) NOT NULL,
    reason VARCHAR(255),
    revision_reason VARCHAR(255),
    reconciled_by_id BIGINT NOT NULL,
    reconciled_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_daily_cash_reconciliations PRIMARY KEY (id),
    CONSTRAINT uq_daily_cash_reconciliations_business_date_version UNIQUE (business_date, version),
    CONSTRAINT ck_daily_cash_reconciliations_status CHECK (status IN ('CURRENT', 'SUPERSEDED')),
    CONSTRAINT ck_daily_cash_reconciliations_opening_cash CHECK (opening_cash >= 0),
    CONSTRAINT ck_daily_cash_reconciliations_cash_sales CHECK (cash_sales >= 0),
    CONSTRAINT ck_daily_cash_reconciliations_cash_expenses CHECK (cash_expenses >= 0),
    CONSTRAINT ck_daily_cash_reconciliations_actual_cash CHECK (actual_cash >= 0),
    CONSTRAINT ck_daily_cash_reconciliations_version CHECK (version >= 1),
    CONSTRAINT ck_daily_cash_reconciliations_expected_cash CHECK (expected_cash = opening_cash + cash_sales - cash_expenses),
    CONSTRAINT ck_daily_cash_reconciliations_difference CHECK (difference = actual_cash - expected_cash),
    CONSTRAINT ck_daily_cash_reconciliations_reason CHECK (difference = 0 OR reason IS NOT NULL),
    CONSTRAINT ck_daily_cash_reconciliations_revision_reason CHECK (version = 1 OR revision_reason IS NOT NULL)
);

