-- Phân hệ 1 – Quản lý nhân viên: lược đồ PostgreSQL (11 bảng).
-- Nhắm tới PostgreSQL 13 trở lên (btree_gist là extension "trusted" từ bản 13).
-- Mới chạy thử trên PostgreSQL 18.3 qua PGlite (WASM); chưa thử trên server cài riêng hay bản 13–17: xem README mục 7.
-- Quy ước: tên bảng số nhiều snake_case; khóa chính id BIGINT; khóa ngoại <thực thể>_id BIGINT;
-- thời điểm TIMESTAMPTZ; múi giờ vận hành Asia/Ho_Chi_Minh; trạng thái VARCHAR + CHECK (JPA: @Enumerated(STRING)).

CREATE EXTENSION IF NOT EXISTS btree_gist;

-- Bộ phận
CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    department_name VARCHAR(50) NOT NULL,
    CONSTRAINT pk_departments PRIMARY KEY (id),
    CONSTRAINT uq_departments_name UNIQUE (department_name)
);

-- Nhân viên (hồ sơ nhân sự, không chứa thông tin đăng nhập)
CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    employee_code VARCHAR(20) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    gender VARCHAR(10),
    date_of_birth DATE,
    phone VARCHAR(15) NOT NULL,
    email VARCHAR(100),
    address VARCHAR(255),
    hire_date DATE NOT NULL,
    end_date DATE,
    work_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    department_id BIGINT NOT NULL,
    CONSTRAINT pk_employees PRIMARY KEY (id),
    CONSTRAINT uq_employees_code UNIQUE (employee_code),
    CONSTRAINT fk_employees_department FOREIGN KEY (department_id) REFERENCES departments (id) ON DELETE RESTRICT,
    CONSTRAINT ck_employees_status CHECK (work_status IN ('ACTIVE', 'ON_LEAVE', 'RESIGNED')),
    CONSTRAINT ck_employees_end_date CHECK (
        (work_status = 'RESIGNED') = (end_date IS NOT NULL)
        AND (end_date IS NULL OR end_date >= hire_date)
    )
);
CREATE INDEX ix_employees_department ON employees (department_id);

-- Tài khoản đăng nhập (tối đa một tài khoản cho một nhân viên)
CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    employee_id BIGINT NOT NULL,
    username VARCHAR(50) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    must_change_password BOOLEAN NOT NULL DEFAULT TRUE,
    account_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT pk_accounts PRIMARY KEY (id),
    CONSTRAINT uq_accounts_employee UNIQUE (employee_id),
    CONSTRAINT uq_accounts_username UNIQUE (username),
    CONSTRAINT fk_accounts_employee FOREIGN KEY (employee_id) REFERENCES employees (id) ON DELETE RESTRICT,
    CONSTRAINT ck_accounts_username CHECK (username <> '' AND username = lower(btrim(username))),
    CONSTRAINT ck_accounts_status CHECK (account_status IN ('ACTIVE', 'LOCKED', 'SUSPENDED', 'DISABLED'))
);

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    role_code VARCHAR(30) NOT NULL,
    role_name VARCHAR(50) NOT NULL,
    CONSTRAINT pk_roles PRIMARY KEY (id),
    CONSTRAINT uq_roles_code UNIQUE (role_code)
);

CREATE TABLE permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    permission_code VARCHAR(50) NOT NULL,
    description VARCHAR(255),
    CONSTRAINT pk_permissions PRIMARY KEY (id),
    CONSTRAINT uq_permissions_code UNIQUE (permission_code)
);

-- Bảng trung gian N–M: tài khoản – vai trò
CREATE TABLE account_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    account_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    CONSTRAINT pk_account_roles PRIMARY KEY (id),
    CONSTRAINT uq_account_roles UNIQUE (account_id, role_id),
    CONSTRAINT fk_account_roles_account FOREIGN KEY (account_id) REFERENCES accounts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_account_roles_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE RESTRICT
);

-- Bảng trung gian N–M: vai trò – quyền
CREATE TABLE role_permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    role_id BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    CONSTRAINT pk_role_permissions PRIMARY KEY (id),
    CONSTRAINT uq_role_permissions UNIQUE (role_id, permission_id),
    CONSTRAINT fk_role_permissions_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE RESTRICT,
    CONSTRAINT fk_role_permissions_permission FOREIGN KEY (permission_id) REFERENCES permissions (id) ON DELETE RESTRICT
);

-- Mẫu ca (chỉ là cấu hình; đổi mẫu không làm đổi các phân ca đã tạo)
CREATE TABLE shifts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    shift_name VARCHAR(50) NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    break_minutes INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_shifts PRIMARY KEY (id),
    CONSTRAINT uq_shifts_name UNIQUE (shift_name),
    CONSTRAINT ck_shifts_name CHECK (length(btrim(shift_name)) > 0),
    CONSTRAINT ck_shifts_time CHECK (end_time <> start_time),
    CONSTRAINT ck_shifts_break CHECK (
        break_minutes >= 0
        AND break_minutes <= CASE WHEN end_time > start_time
                                  THEN EXTRACT(EPOCH FROM (end_time - start_time)) / 60
                                  ELSE EXTRACT(EPOCH FROM (end_time - start_time + INTERVAL '24 hours')) / 60 END
    )
);

-- Phân ca: lưu thời gian đã lên lịch (snapshot) tại thời điểm phân công
CREATE TABLE shift_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    employee_id BIGINT NOT NULL,
    shift_id BIGINT NOT NULL,
    work_date DATE NOT NULL,
    scheduled_start_at TIMESTAMPTZ NOT NULL,
    scheduled_end_at TIMESTAMPTZ NOT NULL,
    scheduled_break_minutes INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
    note VARCHAR(255),
    cancel_reason VARCHAR(255),
    cancelled_by_id BIGINT,
    cancelled_at TIMESTAMPTZ,
    CONSTRAINT pk_shift_assignments PRIMARY KEY (id),
    CONSTRAINT fk_shift_assignments_employee FOREIGN KEY (employee_id) REFERENCES employees (id) ON DELETE RESTRICT,
    CONSTRAINT fk_shift_assignments_shift FOREIGN KEY (shift_id) REFERENCES shifts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_shift_assignments_cancelled_by FOREIGN KEY (cancelled_by_id) REFERENCES employees (id) ON DELETE RESTRICT,
    CONSTRAINT ck_shift_assignments_status CHECK (status IN ('SCHEDULED', 'CANCELLED')),
    CONSTRAINT ck_shift_assignments_time CHECK (scheduled_end_at > scheduled_start_at),
    CONSTRAINT ck_shift_assignments_break CHECK (
        scheduled_break_minutes >= 0
        AND scheduled_break_minutes <= EXTRACT(EPOCH FROM (scheduled_end_at - scheduled_start_at)) / 60
    ),
    CONSTRAINT ck_shift_assignments_work_date CHECK (
        work_date = (scheduled_start_at AT TIME ZONE 'Asia/Ho_Chi_Minh')::date
    ),
    CONSTRAINT ck_shift_assignments_cancel CHECK (
        (status = 'SCHEDULED' AND cancel_reason IS NULL AND cancelled_by_id IS NULL AND cancelled_at IS NULL)
        OR (status = 'CANCELLED' AND cancel_reason IS NOT NULL AND length(btrim(cancel_reason)) > 0
            AND cancelled_by_id IS NOT NULL AND cancelled_at IS NOT NULL)
    ),
    CONSTRAINT ex_shift_assignments_no_overlap EXCLUDE USING gist (
        employee_id WITH =,
        tstzrange(scheduled_start_at, scheduled_end_at, '[)') WITH &&
    ) WHERE (status = 'SCHEDULED')
);
CREATE INDEX ix_shift_assignments_work_date ON shift_assignments (work_date, status);
CREATE INDEX ix_shift_assignments_employee_date ON shift_assignments (employee_id, work_date);
CREATE INDEX ix_shift_assignments_shift ON shift_assignments (shift_id);

-- Chấm công: chỉ có dòng khi Manager đã xác nhận (không tự động có mặt)
CREATE TABLE attendances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    shift_assignment_id BIGINT NOT NULL,
    attendance_status VARCHAR(20) NOT NULL,
    actual_start_at TIMESTAMPTZ,
    actual_end_at TIMESTAMPTZ,
    worked_minutes INTEGER NOT NULL,
    note VARCHAR(255),
    confirmed_by_id BIGINT NOT NULL,
    confirmed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_attendances PRIMARY KEY (id),
    CONSTRAINT uq_attendances_assignment UNIQUE (shift_assignment_id),
    CONSTRAINT fk_attendances_assignment FOREIGN KEY (shift_assignment_id) REFERENCES shift_assignments (id) ON DELETE RESTRICT,
    CONSTRAINT fk_attendances_confirmed_by FOREIGN KEY (confirmed_by_id) REFERENCES employees (id) ON DELETE RESTRICT,
    CONSTRAINT ck_attendances_status CHECK (attendance_status IN ('PRESENT', 'ABSENT', 'DIFFERENT_HOURS')),
    CONSTRAINT ck_attendances_minutes CHECK (worked_minutes >= 0),
    CONSTRAINT ck_attendances_absent CHECK (attendance_status <> 'ABSENT' OR worked_minutes = 0),
    CONSTRAINT ck_attendances_bound CHECK (
        attendance_status <> 'DIFFERENT_HOURS'
        OR worked_minutes <= EXTRACT(EPOCH FROM (actual_end_at - actual_start_at)) / 60
    ),
    CONSTRAINT ck_attendances_times CHECK (
        (attendance_status = 'DIFFERENT_HOURS'
            AND actual_start_at IS NOT NULL AND actual_end_at IS NOT NULL AND actual_end_at > actual_start_at)
        OR (attendance_status IN ('PRESENT', 'ABSENT') AND actual_start_at IS NULL AND actual_end_at IS NULL)
    )
);

-- Nhật ký điều chỉnh công: chỉ ghi thêm, không sửa, không xóa
CREATE TABLE attendance_adjustments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    attendance_id BIGINT NOT NULL,
    old_status VARCHAR(20) NOT NULL,
    new_status VARCHAR(20) NOT NULL,
    old_start_at TIMESTAMPTZ,
    new_start_at TIMESTAMPTZ,
    old_end_at TIMESTAMPTZ,
    new_end_at TIMESTAMPTZ,
    old_worked_minutes INTEGER NOT NULL,
    new_worked_minutes INTEGER NOT NULL,
    reason VARCHAR(255) NOT NULL,
    adjusted_by_id BIGINT NOT NULL,
    adjusted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_attendance_adjustments PRIMARY KEY (id),
    CONSTRAINT fk_attendance_adjustments_attendance FOREIGN KEY (attendance_id) REFERENCES attendances (id) ON DELETE RESTRICT,
    CONSTRAINT fk_attendance_adjustments_adjusted_by FOREIGN KEY (adjusted_by_id) REFERENCES employees (id) ON DELETE RESTRICT,
    CONSTRAINT ck_attendance_adjustments_old_status CHECK (old_status IN ('PRESENT', 'ABSENT', 'DIFFERENT_HOURS')),
    CONSTRAINT ck_attendance_adjustments_new_status CHECK (new_status IN ('PRESENT', 'ABSENT', 'DIFFERENT_HOURS')),
    CONSTRAINT ck_attendance_adjustments_minutes CHECK (old_worked_minutes >= 0 AND new_worked_minutes >= 0),
    CONSTRAINT ck_attendance_adjustments_reason CHECK (length(btrim(reason)) > 0)
);
CREATE INDEX ix_attendance_adjustments_attendance ON attendance_adjustments (attendance_id, adjusted_at);

CREATE FUNCTION fn_reject_history_change() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Bảng % là nhật ký chỉ ghi thêm, không được % dòng', TG_TABLE_NAME, TG_OP;
END;
$$;

CREATE TRIGGER trg_attendance_adjustments_append_only
BEFORE UPDATE OR DELETE ON attendance_adjustments
FOR EACH ROW EXECUTE FUNCTION fn_reject_history_change();

-- Bảng công không có bảng riêng: tổng hợp theo ngày từ chấm công (một ngày nhiều ca vẫn là một dòng)
CREATE VIEW v_daily_timesheets AS
SELECT sa.employee_id,
       sa.work_date,
       COUNT(*) FILTER (WHERE a.attendance_status IN ('PRESENT', 'DIFFERENT_HOURS')) AS shifts_worked,
       COUNT(*) FILTER (WHERE a.attendance_status = 'ABSENT') AS shifts_absent,
       SUM(a.worked_minutes) AS worked_minutes
FROM attendances a
JOIN shift_assignments sa ON sa.id = a.shift_assignment_id
GROUP BY sa.employee_id, sa.work_date;

-- Quyền hiệu lực của tài khoản = hợp quyền của mọi vai trò được gán
CREATE VIEW v_account_permissions AS
SELECT DISTINCT ar.account_id, p.permission_code
FROM account_roles ar
JOIN role_permissions rp ON rp.role_id = ar.role_id
JOIN permissions p ON p.id = rp.permission_id;

